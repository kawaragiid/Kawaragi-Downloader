const SERVER_URL = "http://127.0.0.1:65432";
let isPolling = false;
let isConnected = false;

// Daftar domain utama platform video agar short-link (youtu.be, vt.tiktok.com, b23.tv, fb.watch) tetap mendapat cookies lengkap
const CORE_VIDEO_DOMAINS = [
    "youtube.com",
    "google.com",
    "bilibili.com",
    "bilibili.tv",
    "tiktok.com",
    "instagram.com",
    "facebook.com",
    "x.com",
    "twitter.com",
    "twitch.tv",
    "vimeo.com",
    "dailymotion.com",
    "soundcloud.com",
    "pinterest.com",
    "reddit.com"
];

function extractBaseDomain(urlStr) {
    try {
        const urlObj = new URL(urlStr);
        let host = urlObj.hostname.replace(/^www\./, "");
        const parts = host.split(".");
        if (parts.length > 2) {
            // Contoh: m.youtube.com -> youtube.com
            const lastTwo = parts.slice(-2).join(".");
            if (!["co.id", "co.uk", "com.br", "co.jp", "com.au"].includes(lastTwo)) {
                host = lastTwo;
            }
        }
        return host;
    } catch (e) {
        return "";
    }
}

async function buildNetscapeCookies(targetUrl) {
    let netscapeCookies = "# Netscape HTTP Cookie File\n# Generated by Kawaragi Trigger v2.0\n\n";
    const seen = new Set();
    const domainsToFetch = new Set(CORE_VIDEO_DOMAINS);

    if (targetUrl && targetUrl !== "ALL") {
        const baseDom = extractBaseDomain(targetUrl);
        if (baseDom) {
            domainsToFetch.add(baseDom);
        }
    }

    try {
        const allCookies = await chrome.cookies.getAll({});
        for (const c of allCookies) {
            const cleanCookieDomain = c.domain.replace(/^\./, "");
            let shouldInclude = (targetUrl === "ALL");

            if (!shouldInclude) {
                for (const d of domainsToFetch) {
                    if (cleanCookieDomain === d || cleanCookieDomain.endsWith("." + d)) {
                        shouldInclude = true;
                        break;
                    }
                }
            }

            if (shouldInclude) {
                const key = `${c.domain}|${c.path}|${c.name}`;
                if (seen.has(key)) continue;
                seen.add(key);

                const domainStr = c.domain.startsWith(".") ? c.domain : "." + c.domain;
                const flag = "TRUE";
                const path = c.path || "/";
                const secure = c.secure ? "TRUE" : "FALSE";
                const expiration = c.expirationDate ? Math.round(c.expirationDate) : Math.floor(Date.now() / 1000) + 86400 * 30;
                const name = (c.name || "").replace(/[\r\n\t]/g, "");
                const value = (c.value || "").replace(/[\r\n\t]/g, "");
                if (name) {
                    netscapeCookies += `${domainStr}\t${flag}\t${path}\t${secure}\t${expiration}\t${name}\t${value}\n`;
                }
            }
        }
    } catch (e) {
        console.error("Gagal mengekstrak cookies:", e);
    }

    return {
        cookies: netscapeCookies,
        count: seen.size,
        userAgent: navigator.userAgent
    };
}

async function processTask(targetUrl) {
    const result = await buildNetscapeCookies(targetUrl);
    try {
        const res = await fetch(`${SERVER_URL}/submit-cookies`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
                cookies: result.cookies,
                count: result.count,
                userAgent: result.userAgent,
                url: targetUrl
            })
        });
        return res.ok;
    } catch (e) {
        console.error("Gagal mengirim cookies ke Desktop:", e);
        return false;
    }
}

async function sendTabToDesktop(tabUrl, tabTitle) {
    const result = await buildNetscapeCookies(tabUrl);
    try {
        const res = await fetch(`${SERVER_URL}/send-tab`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
                url: tabUrl,
                title: tabTitle || "",
                cookies: result.cookies,
                count: result.count,
                userAgent: result.userAgent
            })
        });
        return res.ok;
    } catch (e) {
        console.error("Gagal mengirim tab ke Desktop:", e);
        return false;
    }
}

async function startPolling() {
    if (isPolling) return;
    isPolling = true;

    while (isPolling) {
        try {
            // Panggil API Chrome untuk mereset timer 30 detik Service Worker Manifest V3
            await chrome.runtime.getPlatformInfo();

            const controller = new AbortController();
            const timeoutId = setTimeout(() => controller.abort(), 8000);

            const response = await fetch(`${SERVER_URL}/get-task`, {
                signal: controller.signal,
                cache: "no-store"
            });
            clearTimeout(timeoutId);

            if (response.ok) {
                isConnected = true;
                chrome.action.setBadgeText({ text: "ON" });
                chrome.action.setBadgeBackgroundColor({ color: "#9ece6a" });

                const task = await response.json();
                if (task && task.url) {
                    console.log("Tugas masuk dari Desktop:", task.url);
                    await processTask(task.url);
                }
            } else {
                isConnected = false;
                chrome.action.setBadgeText({ text: "" });
            }
        } catch (e) {
            isConnected = false;
            chrome.action.setBadgeText({ text: "" });
            await new Promise(resolve => setTimeout(resolve, 1500));
        }
    }
}

// Listener pesan dari Popup UI
chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (msg.action === "check_status") {
        fetch(`${SERVER_URL}/ping`, { cache: "no-store" })
            .then(r => r.json())
            .then(data => {
                isConnected = true;
                startPolling();
                sendResponse({ connected: true, status: data.status || "ready" });
            })
            .catch(() => {
                isConnected = false;
                sendResponse({ connected: false });
            });
        return true;
    }

    if (msg.action === "sync_cookies") {
        processTask(msg.url || "ALL").then(ok => {
            sendResponse({ success: ok });
        });
        return true;
    }

    if (msg.action === "send_tab") {
        sendTabToDesktop(msg.url, msg.title).then(ok => {
            sendResponse({ success: ok });
        });
        return true;
    }
});

// Pastikan Service Worker selalu hidup dan terhubung kembali
chrome.alarms.create("keepAlive", { periodInMinutes: 0.5 });
chrome.alarms.onAlarm.addListener(() => {
    chrome.runtime.getPlatformInfo();
    startPolling();
});

chrome.runtime.onStartup.addListener(() => startPolling());
chrome.runtime.onInstalled.addListener(() => startPolling());
chrome.tabs.onActivated.addListener(() => startPolling());
chrome.tabs.onUpdated.addListener(() => startPolling());

startPolling();